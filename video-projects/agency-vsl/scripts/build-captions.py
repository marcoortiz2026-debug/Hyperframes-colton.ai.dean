#!/usr/bin/env python3
"""Build assets/captions.js from the A-roll transcript.

Captions follow what the speaker actually said (not the script). Only ASR
spelling errors are corrected, using the script as the reference. Words are
grouped into short phrases for phone-size legibility; keywords are tagged
for accent (benefit) or warn (pain) colour.

    python3 scripts/build-captions.py   # from video-projects/agency-vsl
"""
import json

SRC = "assets/a-roll.transcript.json"
OUT = "assets/captions.js"
MAX_WORDS = 4
GAP_BREAK = 0.28   # a pause this long starts a new group
TAIL = 0.25        # how long the last group of a phrase lingers

# (spoken tokens as transcribed) -> corrected tokens. Timing of the replaced
# span is spread evenly over the new tokens.
FIXES = [
    (["an", "inch"], ["in", "his"]),
    (["Angie,"], ["Angi,"]),
    (["your", "home", "advisory,"], ["HomeAdvisor,"]),
    (["paper", "estimate"], ["pay-per-estimate"]),
    (["charge"], ["charged"]),
    (["On", "recall,"], ["On", "our", "call,"]),
    (["and", "will", "do"], ["and", "we'll", "do"]),
    (["50K"], ["$50K"]),
    (["9x"], ["9X"]),
    (["30", "day"], ["30-day"]),
]

ACCENT = {"hvac", "results", "results.", "results,", "$300,000", "$50k", "profit", "$180,000",
          "free", "free.", "close,", "exclusive", "9x", "risk", "30-day", "trial.",
          "booked.", "money.", "wealthiest", "targeted", "branded", "directly"}
WARN = {"thousands", "retainers", "charged", "competing", "multiple"}


def apply_fixes(words):
    out, i = [], 0
    while i < len(words):
        for src, dst in FIXES:
            seg = [w["text"] for w in words[i:i + len(src)]]
            if seg == src:
                a, b = words[i]["start"], words[i + len(src) - 1]["end"]
                step = (b - a) / len(dst)
                out += [{"text": t, "start": round(a + k * step, 3), "end": round(a + (k + 1) * step, 3)}
                        for k, t in enumerate(dst)]
                i += len(src)
                break
        else:
            out.append(words[i])
            i += 1
    return out


def kind(token):
    t = token.lower()
    if t in ACCENT or t.strip(".,?!") in ACCENT:
        return "a"
    if t in WARN or t.strip(".,?!") in WARN:
        return "w"
    return ""


def main():
    words = apply_fixes(json.load(open(SRC)))
    groups, cur = [], []
    for i, w in enumerate(words):
        cur.append(w)
        nxt = words[i + 1] if i + 1 < len(words) else None
        end_phrase = w["text"][-1] in ".,?!"
        gap = nxt and nxt["start"] - w["end"] >= GAP_BREAK
        # let a phrase run to MAX_WORDS+1 rather than orphan its last word
        closes_next = nxt and nxt["text"][-1] in ".,?!" and len(cur) == MAX_WORDS
        if not nxt or end_phrase or gap or (len(cur) >= MAX_WORDS and not closes_next):
            groups.append(cur)
            cur = []
    caps = []
    for gi, g in enumerate(groups):
        nxt_start = groups[gi + 1][0]["start"] if gi + 1 < len(groups) else g[-1]["end"] + 0.6
        end = min(nxt_start, g[-1]["end"] + TAIL)
        caps.append({
            "start": round(g[0]["start"], 3),
            "end": round(min(max(end, g[0]["start"] + 0.4), nxt_start), 3),
            "words": [{"t": w["text"], "s": round(w["start"], 3), "k": kind(w["text"])} for w in g],
        })
    with open(OUT, "w") as f:
        f.write("// Generated by scripts/build-captions.py from a-roll.transcript.json. Do not edit.\n")
        f.write("window.CAPTIONS = " + json.dumps(caps, separators=(",", ":")) + ";\n")
    print(f"{len(words)} words -> {len(caps)} caption groups -> {OUT}")
    print(" | ".join(" ".join(w["t"] for w in c["words"]) for c in caps[:40]))


if __name__ == "__main__":
    main()
