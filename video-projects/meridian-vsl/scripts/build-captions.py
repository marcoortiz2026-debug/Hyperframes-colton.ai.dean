#!/usr/bin/env python3
"""Build assets/captions.js from the transcripts of the cut (body + CTA).

Captions follow what Jordan actually said. Only ASR spelling/word-boundary
errors are corrected (checked against both Parakeet and Whisper on the source
takes). Words are grouped into short phrases for phone-size legibility;
keywords are tagged for accent (benefit) or warn (pain) colour.

    python3 scripts/build-captions.py   # from video-projects/meridian-vsl
"""
import json

BODY = "cut/tr-aroll/transcript.json"
CTA = "cut/tr-cta/transcript.json"
plan = json.load(open("cut/edit-plan.json"))
CTA_AT = sum(k["f1"] - k["f0"] for k in plan["keep"]) / plan["fps"]
OUT = "assets/captions.js"
MAX_WORDS = 4
GAP_BREAK = 0.28
TAIL = 0.25

FIXES = [
    (["fuzzy", "haired"], ["fuzzy", "head"]),
    (["and", "thin", "to", "become"], ["and", "thinks", "he's", "gonna", "become"]),
    (["Anges,"], ["Angie's", "List,"]),
    (["home", "advisor,"], ["HomeAdvisor,"]),
    (["thumbtack,"], ["Thumbtack,"]),
    (["you.", "That", "generating"], ["you", "that", "generating"]),
    (["nitty", "gritty"], ["nitty-gritty"]),
    (["someone", "call", "Jaden,"], ["someone", "called", "Jordan,"]),
]

ACCENT = {"side", "good", "seven", "eight", "figure", "construction", "estimates", "work", "opportunities",
          "predictably", "scaling", "pipeline", "guarantee", "dialed", "close", "great", "fit", "money",
          "results", "numbers", "economics", "execute", "abundance", "call", "costs", "charge", "serious"}
WARN = {"$5,000", "retainer", "bad", "scammed", "angie's", "list", "homeadvisor", "thumbtack", "burning", "fire",
        "ablaze", "name", "phone", "pick", "dispute", "pitch", "magic", "headache"}


def apply_fixes(words):
    out, i = [], 0
    while i < len(words):
        for src, dst in FIXES:
            seg = [w["text"] for w in words[i:i + len(src)]]
            if seg == src:
                a, b = words[i]["start"], words[i + len(src) - 1]["end"]
                step = (b - a) / len(dst)
                out += [{"text": t, "start": round(a + k * step, 3), "end": round(a + (k + 1) * step, 3)}
                        for k, t in enumerate(dst)]
                i += len(src)
                break
        else:
            out.append(words[i])
            i += 1
    return out


def kind(token, prev):
    """prev = the few words before. A benefit word after "not" ("We're not gonna
    close for you") is not a benefit, and "name" is pain only as "a name"."""
    t = token.lower().strip(".,?!")
    p = [w.lower().strip(".,?!") for w in prev]
    if t == "name" and p[-1:] != ["a"]:
        return ""
    if t in ACCENT and "not" not in p[-3:]:
        return "a"
    if t in WARN:
        return "w"
    return ""


def group(words):
    groups, cur = [], []
    for i, w in enumerate(words):
        cur.append(w)
        nxt = words[i + 1] if i + 1 < len(words) else None
        end_phrase = w["text"][-1] in ".,?!"
        gap = nxt and nxt["start"] - w["end"] >= GAP_BREAK
        closes_next = nxt and nxt["text"][-1] in ".,?!" and len(cur) == MAX_WORDS
        if not nxt or end_phrase or gap or (len(cur) >= MAX_WORDS and not closes_next):
            groups.append(cur)
            cur = []
    return groups


def main():
    body = apply_fixes(json.load(open(BODY)))
    cta = [dict(w, start=w["start"] + CTA_AT, end=w["end"] + CTA_AT) for w in apply_fixes(json.load(open(CTA)))]
    words = body + cta
    for i, w in enumerate(words):
        w["k"] = kind(w["text"], [x["text"] for x in words[max(0, i - 3):i]])
    groups = group(body) + group(cta)
    caps = []
    for gi, g in enumerate(groups):
        nxt_start = groups[gi + 1][0]["start"] if gi + 1 < len(groups) else g[-1]["end"] + 0.6
        end = min(nxt_start, g[-1]["end"] + TAIL)
        caps.append({
            "start": round(g[0]["start"], 3),
            "end": round(min(max(end, g[0]["start"] + 0.4), nxt_start), 3),
            "words": [{"t": w["text"], "s": round(w["start"], 3), "k": w["k"]} for w in g],
        })
    with open(OUT, "w") as f:
        f.write("// Generated by scripts/build-captions.py from the cut transcripts. Do not edit.\n")
        f.write("window.CAPTIONS = " + json.dumps(caps, separators=(",", ":")) + ";\n")
    print(f"{len(body) + len(cta)} words -> {len(caps)} caption groups -> {OUT} (CTA at {CTA_AT:.3f}s)")
    print(" | ".join(" ".join(w["t"] for w in c["words"]) for c in caps))


if __name__ == "__main__":
    main()
